  function detect() {
    try {
      const saved = localStorage.getItem("lang");
      if (SUPPORTED.includes(saved)) return saved;
    } catch {}
    const prefs = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || "en"];
    for (const l of prefs) {
      const code = String(l).slice(0, 2).toLowerCase();
      if (SUPPORTED.includes(code)) return code;
    }
    return "en";
  }

  let lang = detect();

  function t(key, vars) {
    let k = key;
    if (vars && typeof vars.n === "number") {
      const pk = key + (vars.n === 1 ? "_one" : "_other");
      if (DICT[lang][pk] || DICT.en[pk]) k = pk;
    }
    let s = DICT[lang][k] ?? DICT.en[k] ?? key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, v) => (v in vars ? vars[v] : m));
    return s;
  }

  function apply(root = document) {
    document.documentElement.lang = lang;
    root.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = t(el.dataset.i18n)));
    root.querySelectorAll("[data-i18n-ph]").forEach((el) => (el.placeholder = t(el.dataset.i18nPh)));
    root.querySelectorAll("[data-i18n-aria]").forEach((el) => el.setAttribute("aria-label", t(el.dataset.i18nAria)));
    root.querySelectorAll("select.lang-select").forEach((sel) => {
      if (!sel.options.length) {
        const compact = sel.classList.contains("compact");
        sel.innerHTML = SUPPORTED.map((c) => `<option value="${c}">${compact ? c.toUpperCase() : `${c.toUpperCase()} · ${NAMES[c]}`}</option>`).join("");
        sel.addEventListener("change", () => setLang(sel.value));
      }
      sel.value = lang;
      sel.setAttribute("aria-label", t("lang.label"));
    });
    document.title = t("app.title");
  }

  function setLang(l) {
    if (!SUPPORTED.includes(l) || l === lang) { apply(); return; }
    lang = l;
    try { localStorage.setItem("lang", l); } catch {}
    apply();
    window.dispatchEvent(new CustomEvent("langchange", { detail: l }));
  }

